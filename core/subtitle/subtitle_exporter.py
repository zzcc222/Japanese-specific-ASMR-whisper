# -*- coding: utf-8 -*-
"""
ASMR Whisper Studio - 字幕格式生成与导出引擎 (Subtitle 子包)
- 支持 SRT、VTT、TXT、ASS (含逐词卡拉OK高亮样式与自定义排版样式)
- 支持将微调后的字幕条目回写保存至磁盘 (save_subtitle_items)
- 毫秒与百分秒高精度四舍五入对齐
"""

import os
from typing import Any, Dict, List, Optional

from ..nlp.text_cleaner import clean_sub_text, is_pure_punctuation_or_noise


def _hex_to_ass_color(hex_color: str, default: str = "&H00FFE8F5") -> str:
    h = str(hex_color or "").strip().lstrip("#")
    if len(h) != 6:
        return default
    r, g, b = h[0:2].upper(), h[2:4].upper(), h[4:6].upper()
    return f"&H00{b}{g}{r}"


def format_timestamp(seconds: float, format_type: str = "srt") -> str:
    """将秒数转为时间戳字符串 (srt: HH:MM:SS,mmm ; vtt: HH:MM:SS.mmm ; ass: H:MM:SS.cc)"""
    try:
        seconds = float(seconds or 0.0)
    except (ValueError, TypeError):
        seconds = 0.0
    if seconds < 0:
        seconds = 0.0

    if format_type == "ass":
        total_centis = int(round(seconds * 100.0))
        centis = total_centis % 100
        total_secs = total_centis // 100
        secs = total_secs % 60
        total_mins = total_secs // 60
        mins = total_mins % 60
        hrs = total_mins // 60
        return f"{hrs:d}:{mins:02d}:{secs:02d}.{centis:02d}"

    total_millis = int(round(seconds * 1000.0))
    millis = total_millis % 1000
    total_secs = total_millis // 1000
    secs = total_secs % 60
    total_mins = total_secs // 60
    mins = total_mins % 60
    hrs = total_mins // 60

    if format_type == "srt":
        return f"{hrs:02d}:{mins:02d}:{secs:02d},{millis:03d}"
    return f"{hrs:02d}:{mins:02d}:{secs:02d}.{millis:03d}"


def write_custom_ass(
    ass_path: str,
    segments: List[Dict[str, Any]],
    karaoke: bool = False,
    style: Optional[Dict[str, Any]] = None,
):
    """生成兼具美观与阅读舒适度的 ASMR 专用 ASS 字幕 (精准同步版)"""
    if style and isinstance(style, dict):
        font_name = str(style.get("font_family", "Meiryo") or "Meiryo").replace(",", "")
        font_size = int(style.get("font_size", 48) or 48)
        pri_col = _hex_to_ass_color(style.get("color_hex", ""), "&H00FFE8F5")
        out_col = _hex_to_ass_color(style.get("outline_hex", ""), "&H004A154B")
        outline_w = round(float(style.get("outline_width", 3.5) if style.get("outline_width") is not None else 3.5), 1)
        align_val = int(style.get("align", 2) or 2)
        margin_v = int(style.get("margin_v", 60) or 60)
        style_line = (
            f"Style: ASMR_Whisper,{font_name},{font_size},{pri_col},&H00FF99CC,{out_col},&HB01A0520,"
            f"-1,0,0,0,100,100,2,0,1,{outline_w},2,{align_val},40,40,{margin_v},1"
        )
    else:
        style_line = (
            "Style: ASMR_Whisper,Meiryo,48,&H00FFE8F5,&H00FF99CC,&H004A154B,&HB01A0520,"
            "-1,0,0,0,100,100,2,0,1,3.5,2,2,40,40,60,1"
        )

    header = f"""[Script Info]
; Script generated by ASMR Whisper Studio for RTX 5070
Title: ASMR Japanese Whisper Subtitles
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.601
PlayResX: 1920
PlayResY: 1080

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
{style_line}

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    os.makedirs(os.path.dirname(os.path.abspath(ass_path)), exist_ok=True)
    with open(ass_path, "w", encoding="utf-8-sig") as f:
        f.write(header)
        for seg in segments:
            start_str = format_timestamp(seg.get("start", 0.0), "ass")
            end_str = format_timestamp(seg.get("end", 0.0), "ass")
            raw_text = str(seg.get("text", "")).replace("\n", " ")

            if karaoke and seg.get("words"):
                karaoke_parts = []
                words = seg["words"]
                try:
                    seg_start = float(seg.get("start", 0.0) or 0.0)
                except (ValueError, TypeError):
                    seg_start = 0.0

                def _get_w_val(word_obj, key, default=0.0):
                    if isinstance(word_obj, dict):
                        return word_obj.get(key, default)
                    return getattr(word_obj, key, default)

                first_w_start = float(_get_w_val(words[0], "start", seg_start) or seg_start)
                first_gap = int(round((first_w_start - seg_start) * 100))
                if first_gap > 2:
                    karaoke_parts.append(f"{{\\k{first_gap}}}")

                for i, w in enumerate(words):
                    w_s = float(_get_w_val(w, "start", 0.0) or 0.0)
                    w_e = float(_get_w_val(w, "end", w_s) or w_s)
                    duration_cs = max(1, int(round((w_e - w_s) * 100)))
                    w_text = str(_get_w_val(w, "word", "") or "")
                    cleaned_word = w_text.replace("{", "").replace("}", "")
                    karaoke_parts.append(f"{{\\k{duration_cs}}}{cleaned_word}")

                    if i + 1 < len(words):
                        next_s = float(_get_w_val(words[i + 1], "start", w_e) or w_e)
                        gap = int(round((next_s - w_e) * 100))
                        if gap > 2:
                            karaoke_parts.append(f"{{\\k{gap}}}")

                dialogue_text = "".join(karaoke_parts)
            else:
                dialogue_text = raw_text

            f.write(f"Dialogue: 0,{start_str},{end_str},ASMR_Whisper,,0,0,0,,{dialogue_text}\n")


def save_subtitle_items(
    file_path: str,
    items: List[Dict[str, Any]],
    style: Optional[Dict[str, Any]] = None,
) -> bool:
    """
    将压制工作台编辑后的字幕条目列表 (含 start_ms, end_ms, text) 回写保存至原字幕文件 (.srt / .vtt / .ass)
    """
    if not file_path:
        return False
    ext = os.path.splitext(file_path)[1].lower()
    os.makedirs(os.path.dirname(os.path.abspath(file_path)), exist_ok=True)

    def _get_start_ms(x: Dict[str, Any]) -> int:
        if "start_ms" in x:
            return int(x["start_ms"])
        return int(round(float(x.get("start", 0.0)) * 1000))

    def _get_end_ms(x: Dict[str, Any], default_s_ms: int) -> int:
        if "end_ms" in x:
            return int(x["end_ms"])
        if "end" in x:
            return int(round(float(x["end"]) * 1000))
        return default_s_ms + 1000

    sorted_items = sorted(items, key=_get_start_ms)
    segments: List[Dict[str, Any]] = []
    fmt_type = "ass" if ext in (".ass", ".ssa") else ("vtt" if ext == ".vtt" else "srt")

    for it in sorted_items:
        s_ms = max(0, _get_start_ms(it))
        e_ms = max(s_ms + 50, _get_end_ms(it, s_ms))
        txt = str(it.get("text", "")).strip()
        if not txt:
            continue
        s_sec = s_ms / 1000.0
        e_sec = e_ms / 1000.0
        it["start_ms"] = s_ms
        it["end_ms"] = e_ms
        it["start_str"] = format_timestamp(s_sec, fmt_type)
        it["end_str"] = format_timestamp(e_sec, fmt_type)
        segments.append({"start": s_sec, "end": e_sec, "text": txt})

    if ext in (".ass", ".ssa"):
        write_custom_ass(file_path, segments, karaoke=False, style=style)
    elif ext == ".vtt":
        with open(file_path, "w", encoding="utf-8") as f:
            f.write("WEBVTT\n\n")
            for seg in segments:
                start_str = format_timestamp(seg["start"], "vtt")
                end_str = format_timestamp(seg["end"], "vtt")
                f.write(f"{start_str} --> {end_str}\n{seg['text']}\n\n")
    else:
        with open(file_path, "w", encoding="utf-8-sig") as f:
            for idx, seg in enumerate(segments, 1):
                start_str = format_timestamp(seg["start"], "srt")
                end_str = format_timestamp(seg["end"], "srt")
                f.write(f"{idx}\n{start_str} --> {end_str}\n{seg['text']}\n\n")
    return True


def export_subtitles(
    segments: List[Dict[str, Any]],
    base_path: str,
    export_srt: bool = True,
    export_vtt: bool = False,
    export_txt: bool = True,
    export_ass: bool = True,
    enable_karaoke: bool = False,
) -> List[str]:
    """
    导出标准 SRT, VTT, ASS, TXT 字幕文件
    """
    exported = []
    os.makedirs(os.path.dirname(os.path.abspath(base_path)), exist_ok=True)

    if isinstance(segments, dict):
        segments = segments.get("segments", [])
    if not isinstance(segments, (list, tuple)):
        segments = list(segments) if hasattr(segments, "__iter__") else []

    clean_segs = []
    for s in segments:
        if not isinstance(s, dict):
            continue
        t = clean_sub_text(s.get("text", ""))
        if t and not is_pure_punctuation_or_noise(t):
            try:
                s_start = float(s.get("start", 0.0) or 0.0)
            except (ValueError, TypeError):
                s_start = 0.0
            try:
                s_end = float(s.get("end", 0.0) or 0.0)
            except (ValueError, TypeError):
                s_end = s_start
            clean_segs.append(
                {
                    "start": s_start,
                    "end": s_end,
                    "text": t,
                    "words": s.get("words", []),
                }
            )

    if export_srt:
        srt_path = f"{base_path}.srt"
        with open(srt_path, "w", encoding="utf-8-sig") as f:
            for idx, seg in enumerate(clean_segs, 1):
                start_str = format_timestamp(seg["start"], "srt")
                end_str = format_timestamp(seg["end"], "srt")
                f.write(f"{idx}\n{start_str} --> {end_str}\n{seg['text']}\n\n")
        exported.append(srt_path)

    if export_vtt:
        vtt_path = f"{base_path}.vtt"
        with open(vtt_path, "w", encoding="utf-8") as f:
            f.write("WEBVTT\n\n")
            for seg in clean_segs:
                start_str = format_timestamp(seg["start"], "vtt")
                end_str = format_timestamp(seg["end"], "vtt")
                f.write(f"{start_str} --> {end_str}\n{seg['text']}\n\n")
        exported.append(vtt_path)

    if export_txt:
        txt_path = f"{base_path}.txt"
        with open(txt_path, "w", encoding="utf-8") as f:
            for seg in clean_segs:
                time_header = f"[{format_timestamp(seg['start'], 'srt')} -> {format_timestamp(seg['end'], 'srt')}] "
                f.write(f"{time_header}{seg['text']}\n")
        exported.append(txt_path)

    if export_ass:
        ass_path = f"{base_path}.ass"
        write_custom_ass(ass_path, clean_segs, karaoke=enable_karaoke)
        exported.append(ass_path)

    return exported
